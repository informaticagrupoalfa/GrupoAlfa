-- =============================================================================
-- 006_reestructurar_capacitaciones_paralelos.sql
-- =============================================================================
-- Reestructura el modelo de capacitaciones:
--   cursos_capacitacion -> paralelos
--   nueva tabla capacitaciones
--   materia_curso_capacitacion -> materia_capacitacion
--   asesor_curso_capacitacion -> asesor_paralelo
--
-- IMPORTANTE: los datos académicos actuales son ficticios. Esta migración
-- vacía los cursos y todas sus tablas dependientes antes de reestructurar.
-- No modifica usuarios, estudiantes, apoderados, carreras, facultades ni
-- convocatorias.
-- =============================================================================

BEGIN;

-- -----------------------------------------------------------------------------
-- 1. Vaciar datos ficticios de cursos y dependientes
--    El CASCADE alcanza matriculaciones, clases, asistencias, avances y las
--    tablas puente de materias/asesores.
-- -----------------------------------------------------------------------------
TRUNCATE TABLE public.cursos_capacitacion RESTART IDENTITY CASCADE;

-- -----------------------------------------------------------------------------
-- 2. Nueva tabla capacitaciones
-- -----------------------------------------------------------------------------
CREATE TABLE public.capacitaciones (
    id_capacitacion INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_convocatoria INT NOT NULL,
    fecha_inicio DATE NOT NULL,
    fecha_fin DATE,
    activo BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT chk_capacitaciones_fechas
        CHECK (fecha_fin IS NULL OR fecha_fin >= fecha_inicio),

    CONSTRAINT fk_capacitaciones_convocatorias
        FOREIGN KEY (id_convocatoria)
        REFERENCES public.convocatorias_preuniversitario(id_convocatoria)
        ON UPDATE CASCADE
        ON DELETE RESTRICT
);

COMMENT ON TABLE public.capacitaciones IS
    'Capacitación asociada a una convocatoria y a un rango de fechas.';

CREATE INDEX idx_capacitaciones_convocatoria
    ON public.capacitaciones (id_convocatoria);

-- -----------------------------------------------------------------------------
-- 3. Renombrar cursos_capacitacion -> paralelos
-- -----------------------------------------------------------------------------
ALTER TABLE public.cursos_capacitacion RENAME TO paralelos;
ALTER TABLE public.paralelos RENAME COLUMN id_capacitacion TO id_paralelo;

ALTER TABLE public.paralelos DROP CONSTRAINT IF EXISTS fk_cursos_convocatorias;
ALTER TABLE public.paralelos DROP CONSTRAINT IF EXISTS chk_cursos_capacitacion_fechas;

ALTER TABLE public.paralelos DROP COLUMN IF EXISTS id_convocatoria;
ALTER TABLE public.paralelos DROP COLUMN IF EXISTS fecha_inicio;
ALTER TABLE public.paralelos DROP COLUMN IF EXISTS fecha_fin;

ALTER TABLE public.paralelos RENAME COLUMN nombre TO nombre_paralelo;

ALTER TABLE public.paralelos
    ADD COLUMN id_capacitacion INT,
    ADD COLUMN dias VARCHAR(100);

ALTER TABLE public.paralelos
    ALTER COLUMN id_capacitacion SET NOT NULL,
    ALTER COLUMN activo SET DEFAULT TRUE,
    ALTER COLUMN activo SET NOT NULL;

ALTER TABLE public.paralelos
    ADD CONSTRAINT fk_paralelos_capacitaciones
        FOREIGN KEY (id_capacitacion)
        REFERENCES public.capacitaciones(id_capacitacion)
        ON UPDATE CASCADE
        ON DELETE RESTRICT;

ALTER TABLE public.paralelos
    ADD CONSTRAINT chk_paralelos_horas
        CHECK (hora_inicio IS NULL OR hora_fin IS NULL OR hora_fin > hora_inicio);

ALTER TABLE public.paralelos RENAME CONSTRAINT fk_cursos_aulas TO fk_paralelos_aulas;
ALTER TABLE public.paralelos RENAME CONSTRAINT cursos_capacitacion_pkey TO paralelos_pkey;

COMMENT ON TABLE public.paralelos IS
    'Grupo/paralelo de una capacitación. Define aula, nivel, modalidad, horario y días.';

CREATE INDEX idx_paralelos_capacitacion
    ON public.paralelos (id_capacitacion);

CREATE INDEX idx_paralelos_aula
    ON public.paralelos (id_aula);

-- -----------------------------------------------------------------------------
-- 4. Materias por capacitación
-- -----------------------------------------------------------------------------
DROP TABLE IF EXISTS public.materia_curso_capacitacion CASCADE;

CREATE TABLE public.materia_capacitacion (
    id_asignacion_materia INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_materia INT NOT NULL,
    id_capacitacion INT NOT NULL,

    CONSTRAINT uq_materia_capacitacion
        UNIQUE (id_materia, id_capacitacion),

    CONSTRAINT fk_materia_capacitacion_materia
        FOREIGN KEY (id_materia)
        REFERENCES public.materias(id_materia)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    CONSTRAINT fk_materia_capacitacion_capacitacion
        FOREIGN KEY (id_capacitacion)
        REFERENCES public.capacitaciones(id_capacitacion)
        ON UPDATE CASCADE
        ON DELETE CASCADE
);

CREATE INDEX idx_materia_capacitacion_capacitacion
    ON public.materia_capacitacion (id_capacitacion);

-- -----------------------------------------------------------------------------
-- 5. Asesores por paralelo
-- -----------------------------------------------------------------------------
DROP TABLE IF EXISTS public.asesor_curso_capacitacion CASCADE;

CREATE TABLE public.asesor_paralelo (
    id_asignacion_asesor INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_asesor INT NOT NULL,
    id_paralelo INT NOT NULL,

    CONSTRAINT uq_asesor_paralelo
        UNIQUE (id_asesor, id_paralelo),

    CONSTRAINT fk_asesor_paralelo_asesor
        FOREIGN KEY (id_asesor)
        REFERENCES public.asesores(id_asesor)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    CONSTRAINT fk_asesor_paralelo_paralelo
        FOREIGN KEY (id_paralelo)
        REFERENCES public.paralelos(id_paralelo)
        ON UPDATE CASCADE
        ON DELETE CASCADE
);

CREATE INDEX idx_asesor_paralelo_paralelo
    ON public.asesor_paralelo (id_paralelo);

-- -----------------------------------------------------------------------------
-- 6. Matriculaciones y clases apuntan al paralelo
-- -----------------------------------------------------------------------------
ALTER TABLE public.matriculaciones
    RENAME COLUMN id_curso_capacitacion TO id_paralelo;

ALTER TABLE public.matriculaciones
    RENAME CONSTRAINT fk_matriculaciones_cursos TO fk_matriculaciones_paralelos;

ALTER TABLE public.clases
    RENAME COLUMN id_curso_capacitacion TO id_paralelo;

ALTER TABLE public.clases
    RENAME CONSTRAINT fk_clases_cursos TO fk_clases_paralelos;

ALTER INDEX IF EXISTS public.idx_matriculaciones_curso
    RENAME TO idx_matriculaciones_paralelo;

CREATE INDEX IF NOT EXISTS idx_clases_paralelo
    ON public.clases (id_paralelo);

COMMIT;
