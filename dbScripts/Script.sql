-- =============================================================================
-- 2. TABLA USUARIOS
-- =============================================================================

CREATE TABLE usuarios (
	id_usuario INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nro_carnet INT UNIQUE NOT NULL,
    apellido_paterno VARCHAR(100) NOT NULL,
    apellido_materno VARCHAR(100),
    nombre VARCHAR(100) NOT NULL,
    fecha_nacimiento DATE,
    correo_electronico VARCHAR(150) UNIQUE,
    contraseña VARCHAR(255),
	Usuario_vigente BOOLEAN
);

-- =============================================================================
-- 1. TABLAS BASE
-- =============================================================================


-- -----------------------------------------------------------------------------
-- Tabla: Administrativos
-- -----------------------------------------------------------------------------

CREATE TABLE administrativos (
    id_administrativo INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	id_usuario INT,

	CONSTRAINT fk_administrativos_usuarios
	FOREIGN KEY (id_usuario)
	REFERENCES usuarios(id_usuario)
	ON UPDATE CASCADE
	ON DELETE CASCADE
);


-- -----------------------------------------------------------------------------
-- Tabla: Facultades
-- -----------------------------------------------------------------------------

CREATE TABLE facultades (
    id_facultad INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(150) NOT NULL
);


-- -----------------------------------------------------------------------------
-- Tabla: Aulas
-- -----------------------------------------------------------------------------

CREATE TABLE aulas (
    id_aula INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(20),
    capacidad INT NOT NULL CHECK (capacidad > 0)
);


-- -----------------------------------------------------------------------------
-- Tabla: Asesores
-- -----------------------------------------------------------------------------

CREATE TABLE asesores (
    id_asesor INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	id_usuario INT,
	
	CONSTRAINT fk_asesores_usuarios
        FOREIGN KEY (id_usuario)
        REFERENCES usuarios(id_usuario)
        ON UPDATE CASCADE
        ON DELETE SET NULL
);


-- -----------------------------------------------------------------------------
-- Tabla: Materias
-- -----------------------------------------------------------------------------

CREATE TABLE materias (
    id_materia INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_materia VARCHAR(150) NOT NULL
);

-- -----------------------------------------------------------------------------
-- Tabla: Temas
-- -----------------------------------------------------------------------------
CREATE TABLE temas(
	id_tema INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	id_materia INT,
    nombre_tema VARCHAR(100),

	CONSTRAINT fk_temas_materia
		FOREIGN KEY (id_materia)
		REFERENCES materias(id_materia)
		ON UPDATE CASCADE
		ON DELETE SET NULL	
);

-- -----------------------------------------------------------------------------
-- Tabla: Apoderados
-- -----------------------------------------------------------------------------

CREATE TABLE apoderados (
    id_apoderado INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	id_usuario INT,
    celular VARCHAR(20),

	
	CONSTRAINT fk_apoderados_usuarios
	FOREIGN KEY (id_usuario)
	REFERENCES usuarios(id_usuario)
	ON UPDATE CASCADE
	ON DELETE CASCADE
);


-- -----------------------------------------------------------------------------
-- Tabla: Estudiantes
-- -----------------------------------------------------------------------------

CREATE TABLE estudiantes (
    id_estudiante INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	id_usuario INT UNIQUE,
	id_apoderado INT,
    colegio_de_procedencia VARCHAR(150),
    direccion_de_domicilio VARCHAR(255),
    foto BYTEA,

	CONSTRAINT fk_estudiantes_usuario
		FOREIGN KEY (id_usuario)
		REFERENCES usuarios(id_usuario)
		ON UPDATE CASCADE
		ON DELETE CASCADE,
	CONSTRAINT fk_estudiantes_apoderado
		FOREIGN KEY (id_apoderado)
		REFERENCES apoderados(id_apoderado)
		ON UPDATE CASCADE
		ON DELETE SET NULL
);

-- -----------------------------------------------------------------------------
-- Tabla: Inscripciones
-- -----------------------------------------------------------------------------

CREATE TABLE inscripciones(
	id_inscripcion INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	id_administrativo INT,
	id_estudiante INT,
	id_carrera INT,
	
    como_se_entero_de_nosotros VARCHAR(255),
    como_se_entero_detalle VARCHAR(255),
    recalculo BOOLEAN DEFAULT FALSE,
    preparacion_previa BOOLEAN DEFAULT FALSE,
    tiempo_de_preparacion_meses INT DEFAULT 0,
    lugar_de_preparacion VARCHAR(255),

    nro_comprobante INT,
    nro_credencial INT,
    inicio_clases DATE,
    modalidad VARCHAR(50),
    horario VARCHAR(100),
    grupo VARCHAR(50),

    apellido_paterno VARCHAR(100),
    apellido_materno VARCHAR(100),
    nombre VARCHAR(100),
    edad INT,
    correo_electronico VARCHAR(150),
    colegio_de_procedencia VARCHAR(150),
    direccion_de_domicilio VARCHAR(255),
    firma TEXT,

    apoderado_nombre_completo VARCHAR(200),
    apoderado_celular VARCHAR(20),
    apoderado_parentesco VARCHAR(100),

    elaborado_por VARCHAR(150),
    sucursal VARCHAR(100),
    fecha_registro DATE DEFAULT CURRENT_DATE,

	CONSTRAINT fk_inscripciones_administrativo
		FOREIGN KEY (id_administrativo)
		REFERENCES administrativos(id_administrativo)
		ON UPDATE CASCADE
		ON DELETE SET NULL,
		
	CONSTRAINT fk_inscripciones_estudiante
		FOREIGN KEY (id_estudiante)
		REFERENCES estudiantes(id_estudiante)
		ON UPDATE CASCADE
		ON DELETE SET NULL
);



-- =============================================================================
-- 3. ROLES Y ASIGNACIÓN DE ROLES
-- =============================================================================


-- -----------------------------------------------------------------------------
-- Tabla: Roles
-- -----------------------------------------------------------------------------

CREATE TABLE roles (
    id_rol INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(50) NOT NULL UNIQUE
);


-- -----------------------------------------------------------------------------
-- Tabla: AsignacionRol
-- -----------------------------------------------------------------------------

CREATE TABLE asignacion_rol (
    id_asignacion_rol INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_rol INT NOT NULL,
    id_usuario INT NOT NULL,

    CONSTRAINT fk_asignacion_rol_rol
        FOREIGN KEY (id_rol)
        REFERENCES roles(id_rol)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT fk_asignacion_rol_usuario
        FOREIGN KEY (id_usuario)
        REFERENCES usuarios(id_usuario)
        ON UPDATE CASCADE
        ON DELETE SET NULL
);


-- =============================================================================
-- 4. TABLAS DE SEGUNDO NIVEL
-- =============================================================================


-- -----------------------------------------------------------------------------
-- Tabla: Carreras
-- -----------------------------------------------------------------------------

CREATE TABLE carreras (
    id_carrera INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_facultad INT NOT NULL,
    nombre VARCHAR(150) NOT NULL,

    CONSTRAINT fk_carreras_facultades
        FOREIGN KEY (id_facultad)
        REFERENCES facultades(id_facultad)
        ON UPDATE CASCADE
        ON DELETE RESTRICT
);

-- Inscripciones referencia carreras, que se crea después de la tabla inscripciones.
ALTER TABLE inscripciones
    ADD CONSTRAINT fk_inscripciones_carrera
    FOREIGN KEY (id_carrera)
    REFERENCES carreras(id_carrera)
    ON UPDATE CASCADE
    ON DELETE SET NULL;


-- -----------------------------------------------------------------------------
-- Tabla: Convocatorias Preuniversitario
-- -----------------------------------------------------------------------------

CREATE TABLE convocatorias_preuniversitario (
    id_convocatoria INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_facultad INT NOT NULL,
    fecha_inicio DATE NOT NULL,

    CONSTRAINT fk_convocatorias_facultades
        FOREIGN KEY (id_facultad)
        REFERENCES facultades(id_facultad)
        ON UPDATE CASCADE
        ON DELETE RESTRICT
);

-- -----------------------------------------------------------------------------
-- Tabla: Examenes de ingreso
-- -----------------------------------------------------------------------------
CREATE TABLE examenes_de_ingreso(
	id_examen_de_ingreso INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	id_convocatoria INT,
	id_materia INT,
	foto BYTEA,

	CONSTRAINT fk_examenes_convocatoria
		FOREIGN KEY (id_convocatoria)
		REFERENCES convocatorias_preuniversitario
		ON UPDATE CASCADE
		ON DELETE SET NULL,
	CONSTRAINT fk_examenes_materia
		FOREIGN KEY (id_materia)
		REFERENCES materias(id_materia)
		ON UPDATE CASCADE
		ON DELETE RESTRICT
);
-- -----------------------------------------------------------------------------
-- Tabla: Contenidos
-- -----------------------------------------------------------------------------
CREATE TABLE contenidos(
	id_contenido INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	id_examen_de_ingreso INT,
	id_tema INT,

	CONSTRAINT fk_contenidos_examen
		FOREIGN KEY (id_examen_de_ingreso)
		REFERENCES examenes_de_ingreso(id_examen_de_ingreso)
		ON UPDATE CASCADE
		ON DELETE SET NULL,
	CONSTRAINT fk_contenidos_tema
		FOREIGN KEY (id_tema)
		REFERENCES temas(id_tema)
		ON UPDATE CASCADE
		ON DELETE SET NULL
);

-- -----------------------------------------------------------------------------
-- Tabla: Materias - Asesores
-- -----------------------------------------------------------------------------

CREATE TABLE materias_asesores (
    id_materia_asesor INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_asesor INT NOT NULL,
    id_materia INT NOT NULL,

    CONSTRAINT fk_matasesores_asesores
        FOREIGN KEY (id_asesor)
        REFERENCES asesores(id_asesor)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    CONSTRAINT fk_matasesores_materia
        FOREIGN KEY (id_materia)
        REFERENCES materias(id_materia)
        ON UPDATE CASCADE
        ON DELETE CASCADE
);


-- =============================================================================
-- 5. RELACIONES ENTRE ESTUDIANTES Y APODERADOS
-- =============================================================================


-- -----------------------------------------------------------------------------
-- Tabla: Postulaciones
-- -----------------------------------------------------------------------------

CREATE TABLE postulaciones (
    id_postulacion INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_estudiante INT NOT NULL,
    id_carrera INT NOT NULL,

    CONSTRAINT fk_postulaciones_estudiantes
        FOREIGN KEY (id_estudiante)
        REFERENCES estudiantes(id_estudiante)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    CONSTRAINT fk_postulaciones_carreras
        FOREIGN KEY (id_carrera)
        REFERENCES carreras(id_carrera)
        ON UPDATE CASCADE
        ON DELETE RESTRICT
);


-- =============================================================================
-- 6. CAPACITACIONES, PARALELOS Y CONVOCATORIAS
-- =============================================================================


-- -----------------------------------------------------------------------------
-- Tabla: Capacitaciones
-- -----------------------------------------------------------------------------

CREATE TABLE capacitaciones (
    id_capacitacion INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_convocatoria INT NOT NULL,
    fecha_inicio DATE NOT NULL,
    fecha_fin DATE,
    activo BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT chk_capacitaciones_fechas
        CHECK (fecha_fin IS NULL OR fecha_fin >= fecha_inicio),

    CONSTRAINT fk_capacitaciones_convocatorias
        FOREIGN KEY (id_convocatoria)
        REFERENCES convocatorias_preuniversitario(id_convocatoria)
        ON UPDATE CASCADE
        ON DELETE RESTRICT
);


-- -----------------------------------------------------------------------------
-- Tabla: Paralelos
-- -----------------------------------------------------------------------------

CREATE TABLE paralelos (
    id_paralelo INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_capacitacion INT NOT NULL,
    id_aula INT NOT NULL,
    nivel VARCHAR(100),
    -- Iniciando, intermedio, avanzado
    nombre_paralelo VARCHAR(150) NOT NULL,
    modalidad VARCHAR(50),
    hora_inicio TIME,
    hora_fin TIME,
    dias VARCHAR(100),
    activo BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT chk_paralelos_horas
        CHECK (hora_inicio IS NULL OR hora_fin IS NULL OR hora_fin > hora_inicio),

    CONSTRAINT fk_paralelos_capacitaciones
        FOREIGN KEY (id_capacitacion)
        REFERENCES capacitaciones(id_capacitacion)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT fk_paralelos_aulas
        FOREIGN KEY (id_aula)
        REFERENCES aulas(id_aula)
        ON UPDATE CASCADE
        ON DELETE RESTRICT
);


-- =============================================================================
-- 7. ASIGNACIONES
-- =============================================================================


-- -----------------------------------------------------------------------------
-- Tabla: Materias por Capacitación
-- -----------------------------------------------------------------------------

CREATE TABLE materia_capacitacion (
    id_asignacion_materia INT
        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    id_materia INT NOT NULL,
    id_capacitacion INT NOT NULL,

    CONSTRAINT uq_materia_capacitacion
        UNIQUE (id_materia, id_capacitacion),

    CONSTRAINT fk_materia_capacitacion_materia
        FOREIGN KEY (id_materia)
        REFERENCES materias(id_materia)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    CONSTRAINT fk_materia_capacitacion_capacitacion
        FOREIGN KEY (id_capacitacion)
        REFERENCES capacitaciones(id_capacitacion)
        ON UPDATE CASCADE
        ON DELETE CASCADE
);


-- -----------------------------------------------------------------------------
-- Tabla: Asesores por Paralelo
-- -----------------------------------------------------------------------------

CREATE TABLE asesor_paralelo (
    id_asignacion_asesor INT
        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    id_asesor INT NOT NULL,
    id_paralelo INT NOT NULL,

    CONSTRAINT uq_asesor_paralelo
        UNIQUE (id_asesor, id_paralelo),

    CONSTRAINT fk_asesor_paralelo_asesor
        FOREIGN KEY (id_asesor)
        REFERENCES asesores(id_asesor)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    CONSTRAINT fk_asesor_paralelo_paralelo
        FOREIGN KEY (id_paralelo)
        REFERENCES paralelos(id_paralelo)
        ON UPDATE CASCADE
        ON DELETE CASCADE
);


-- =============================================================================
-- 8. MATRICULACIONES
-- =============================================================================


CREATE TABLE matriculaciones (
    id_matriculacion INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    id_estudiante INT NOT NULL,
    id_paralelo INT NOT NULL,

    esta_vigente BOOLEAN DEFAULT TRUE,
    nro_comprobante INT,
    nro_credencial INT,

    CONSTRAINT fk_matriculaciones_estudiantes
        FOREIGN KEY (id_estudiante)
        REFERENCES estudiantes(id_estudiante)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT fk_matriculaciones_paralelos
        FOREIGN KEY (id_paralelo)
        REFERENCES paralelos(id_paralelo)
        ON UPDATE CASCADE
        ON DELETE RESTRICT
);


-- =============================================================================
-- 9. CLASES
-- =============================================================================


CREATE TABLE clases (
    id_clase INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	
    id_paralelo INT NOT NULL,
    id_asesor INT NOT NULL,
	id_tema INT,

    inicioClase DATE NOT NULL,

    CONSTRAINT fk_clases_paralelos
        FOREIGN KEY (id_paralelo)
        REFERENCES paralelos(id_paralelo)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    CONSTRAINT fk_clases_asesores
        FOREIGN KEY (id_asesor)
        REFERENCES asesores(id_asesor)
        ON UPDATE CASCADE
        ON DELETE RESTRICT
);

-- =============================================================================
-- 10. Avances
-- =============================================================================
CREATE TABLE avances(
	id_avance INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	id_clase INT,
	id_tema INT,
	
	CONSTRAINT fk_avances_clase
		FOREIGN KEY (id_clase)
		REFERENCES clases(id_clase)
		ON UPDATE CASCADE
		ON DELETE SET NULL,
	
	CONSTRAINT fk_avances_tema
		FOREIGN KEY (id_tema)
		REFERENCES temas(id_tema)
		ON UPDATE CASCADE
		ON DELETE SET NULL
);

-- =============================================================================
-- 10. MENSUALIDADES
-- =============================================================================


CREATE TABLE mensualidades (
    id_mensualidad INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    id_estudiante INT NOT NULL,
    id_administrativo INT NOT NULL,

    fecha_inicio_mensualidad DATE NOT NULL,
    fecha_fin_mensualidad DATE NOT NULL,

    pago NUMERIC(10, 2) NOT NULL CHECK (pago >= 0),

    CONSTRAINT fk_mensualidades_estudiantes
        FOREIGN KEY (id_estudiante)
        REFERENCES estudiantes(id_estudiante)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT fk_mensualidades_administrativos
        FOREIGN KEY (id_administrativo)
        REFERENCES administrativos(id_administrativo)
        ON UPDATE CASCADE
        ON DELETE RESTRICT
);


-- =============================================================================
-- 11. ASISTENCIAS
-- =============================================================================


CREATE TABLE asistencias (
    id_asistencia INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    id_clase INT NOT NULL,
    id_estudiante INT NOT NULL,

    hora_entrada TIMESTAMP NOT NULL,
    salida_antes_de_tiempo TIMESTAMP,
	permiso BOOLEAN,
	razon_permiso VARCHAR(150),

    CONSTRAINT fk_asistencias_clases
        FOREIGN KEY (id_clase)
        REFERENCES clases(id_clase)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    CONSTRAINT fk_asistencias_estudiantes
        FOREIGN KEY (id_estudiante)
        REFERENCES estudiantes(id_estudiante)
        ON UPDATE CASCADE
        ON DELETE CASCADE
);


