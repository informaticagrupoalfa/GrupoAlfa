-- Crea las tablas relacionales y claves foráneas si no existen.
-- No copia, migra ni elimina registros existentes.
-- Modelo: clases -> asesor_paralelo_materia -> asesor + paralelo_materia
--         paralelo_materia -> paralelo + materia

CREATE TABLE IF NOT EXISTS public.paralelo_materia (
    id_paralelo_materia integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_paralelo integer NOT NULL,
    id_materia integer NOT NULL
);

DO $paralelo_materia_constraints$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conrelid = 'public.paralelo_materia'::regclass
          AND conname = 'uq_paralelo_materia'
    ) THEN
        ALTER TABLE public.paralelo_materia
            ADD CONSTRAINT uq_paralelo_materia UNIQUE (id_paralelo, id_materia);
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conrelid = 'public.paralelo_materia'::regclass
          AND conname = 'fk_paralelo_materia_paralelos'
    ) THEN
        ALTER TABLE public.paralelo_materia
            ADD CONSTRAINT fk_paralelo_materia_paralelos
            FOREIGN KEY (id_paralelo) REFERENCES public.paralelos(id_paralelo)
            ON UPDATE CASCADE ON DELETE CASCADE;
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conrelid = 'public.paralelo_materia'::regclass
          AND conname = 'fk_paralelo_materia_materias'
    ) THEN
        ALTER TABLE public.paralelo_materia
            ADD CONSTRAINT fk_paralelo_materia_materias
            FOREIGN KEY (id_materia) REFERENCES public.materias(id_materia)
            ON UPDATE CASCADE ON DELETE CASCADE;
    END IF;
END
$paralelo_materia_constraints$;

CREATE TABLE IF NOT EXISTS public.asesor_paralelo_materia (
    id_asesor_paralelo_materia integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_asesor integer NOT NULL,
    id_paralelo_materia integer NOT NULL
);

-- También cubre la tabla antigua creada por la versión previa del script.
-- Se deja NULL en las filas existentes; no se asignan ni transforman datos.
ALTER TABLE public.asesor_paralelo_materia
    ADD COLUMN IF NOT EXISTS id_paralelo_materia integer;

DO $asesor_paralelo_materia_constraints$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conrelid = 'public.asesor_paralelo_materia'::regclass
          AND conname = 'uq_apm_asesor_paralelo_materia_id'
    ) THEN
        ALTER TABLE public.asesor_paralelo_materia
            ADD CONSTRAINT uq_apm_asesor_paralelo_materia_id
            UNIQUE (id_asesor, id_paralelo_materia);
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conrelid = 'public.asesor_paralelo_materia'::regclass
          AND conname = 'fk_apm_asesores'
    ) THEN
        ALTER TABLE public.asesor_paralelo_materia
            ADD CONSTRAINT fk_apm_asesores
            FOREIGN KEY (id_asesor) REFERENCES public.asesores(id_asesor)
            ON UPDATE CASCADE ON DELETE CASCADE;
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conrelid = 'public.asesor_paralelo_materia'::regclass
          AND conname = 'fk_apm_paralelo_materia'
    ) THEN
        ALTER TABLE public.asesor_paralelo_materia
            ADD CONSTRAINT fk_apm_paralelo_materia
            FOREIGN KEY (id_paralelo_materia)
            REFERENCES public.paralelo_materia(id_paralelo_materia)
            ON UPDATE CASCADE ON DELETE CASCADE;
    END IF;
END
$asesor_paralelo_materia_constraints$;

ALTER TABLE public.clases
    ADD COLUMN IF NOT EXISTS id_asesor_paralelo_materia integer;

DO $clases_constraints$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conrelid = 'public.clases'::regclass
          AND conname = 'fk_clases_asesor_paralelo_materia'
    ) THEN
        ALTER TABLE public.clases
            ADD CONSTRAINT fk_clases_asesor_paralelo_materia
            FOREIGN KEY (id_asesor_paralelo_materia)
            REFERENCES public.asesor_paralelo_materia(id_asesor_paralelo_materia)
            ON UPDATE CASCADE ON DELETE SET NULL;
    END IF;
END
$clases_constraints$;
