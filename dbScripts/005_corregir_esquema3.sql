-- =============================================================================
-- 005_corregir_esquema3.sql
-- =============================================================================
-- Corrige el esquema actual (Esquema3.sql):
--   - Elimina la relación temas -> materias.
--   - Elimina la relación materias -> convocatorias.
--   - Crea materia_facultad (N:N).
--   - Crea materia_facultad_temas (N:N).
--   - Corrige la columna "Activo" de cursos_capacitacion.
--   - Alinea la longitud de temas.nombre_tema.
--   - Corrige el índice de examenes_de_ingreso.
--   - Agrega UNIQUE a tablas puente existentes.
--
-- No modifica inscripciones ni scripts anteriores.
-- =============================================================================

BEGIN;

-- -----------------------------------------------------------------------------
-- 1. Normalizar la columna "Activo" de cursos_capacitacion
-- -----------------------------------------------------------------------------
DO $$
BEGIN
    IF EXISTS (
        SELECT 1
        FROM information_schema.columns
        WHERE table_schema = 'public'
          AND table_name = 'cursos_capacitacion'
          AND column_name = 'Activo'
    ) AND NOT EXISTS (
        SELECT 1
        FROM information_schema.columns
        WHERE table_schema = 'public'
          AND table_name = 'cursos_capacitacion'
          AND column_name = 'activo'
    ) THEN
        ALTER TABLE public.cursos_capacitacion
            RENAME COLUMN "Activo" TO activo;
    END IF;
END $$;

-- -----------------------------------------------------------------------------
-- 2. Alinear la longitud de temas.nombre_tema con el validador actual
-- -----------------------------------------------------------------------------
ALTER TABLE public.temas
    ALTER COLUMN nombre_tema TYPE character varying(150);

-- -----------------------------------------------------------------------------
-- 3. Corregir el índice de examenes_de_ingreso
--    Estaba indexando la PK en lugar de id_convocatoria.
-- -----------------------------------------------------------------------------
DROP INDEX IF EXISTS public.idx_examenes_convocatoria;

CREATE INDEX idx_examenes_convocatoria
    ON public.examenes_de_ingreso (id_convocatoria);

-- -----------------------------------------------------------------------------
-- 4. Eliminar la relación temas -> materias
-- -----------------------------------------------------------------------------
ALTER TABLE public.temas
    DROP CONSTRAINT IF EXISTS fk_temas_materia;

DROP INDEX IF EXISTS public.idx_temas_materia;

ALTER TABLE public.temas
    DROP COLUMN IF EXISTS id_materia;

-- -----------------------------------------------------------------------------
-- 5. Eliminar la relación materias -> convocatorias
-- -----------------------------------------------------------------------------
DROP TABLE IF EXISTS public.convocatoria_materia;

-- -----------------------------------------------------------------------------
-- 6. Crear materia_facultad
--    Cada fila representa una materia ofrecida por una facultad.
--    Ejemplo: Matemática en Ingeniería / Matemática en Medicina.
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.materia_facultad (
    id_materia_facultad integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_materia integer NOT NULL,
    id_facultad integer NOT NULL,

    CONSTRAINT uq_materia_facultad
        UNIQUE (id_materia, id_facultad),

    CONSTRAINT fk_materia_facultad_materia
        FOREIGN KEY (id_materia)
        REFERENCES public.materias(id_materia)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    CONSTRAINT fk_materia_facultad_facultad
        FOREIGN KEY (id_facultad)
        REFERENCES public.facultades(id_facultad)
        ON UPDATE CASCADE
        ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_materia_facultad_facultad
    ON public.materia_facultad (id_facultad);

-- -----------------------------------------------------------------------------
-- 7. Crear materia_facultad_temas
--    Cada fila representa un tema del temario de una materia-facultad.
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.materia_facultad_temas (
    id_materia_facultad_tema integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_materia_facultad integer NOT NULL,
    id_tema integer NOT NULL,

    CONSTRAINT uq_materia_facultad_tema
        UNIQUE (id_materia_facultad, id_tema),

    CONSTRAINT fk_mft_materia_facultad
        FOREIGN KEY (id_materia_facultad)
        REFERENCES public.materia_facultad(id_materia_facultad)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    CONSTRAINT fk_mft_tema
        FOREIGN KEY (id_tema)
        REFERENCES public.temas(id_tema)
        ON UPDATE CASCADE
        ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_mft_tema
    ON public.materia_facultad_temas (id_tema);

COMMENT ON TABLE public.materia_facultad IS
    'Materia ofrecida por una facultad. Permite temarios distintos por facultad.';

COMMENT ON TABLE public.materia_facultad_temas IS
    'Temas que forman el temario de una materia en una facultad.';

-- -----------------------------------------------------------------------------
-- 8. Agregar UNIQUE a tablas puente existentes
-- -----------------------------------------------------------------------------

-- usuario_rol
DELETE FROM public.usuario_rol a
USING public.usuario_rol b
WHERE a.id_asignacion_rol > b.id_asignacion_rol
  AND a.id_usuario = b.id_usuario
  AND a.id_rol = b.id_rol;

ALTER TABLE public.usuario_rol
    DROP CONSTRAINT IF EXISTS uq_usuario_rol_usuario_rol;

ALTER TABLE public.usuario_rol
    ADD CONSTRAINT uq_usuario_rol_usuario_rol
    UNIQUE (id_usuario, id_rol);

-- materia_asesor
DELETE FROM public.materia_asesor a
USING public.materia_asesor b
WHERE a.id_materia_asesor > b.id_materia_asesor
  AND a.id_asesor = b.id_asesor
  AND a.id_materia = b.id_materia;

ALTER TABLE public.materia_asesor
    DROP CONSTRAINT IF EXISTS uq_materia_asesor_asesor_materia;

ALTER TABLE public.materia_asesor
    ADD CONSTRAINT uq_materia_asesor_asesor_materia
    UNIQUE (id_asesor, id_materia);

-- asesor_curso_capacitacion
DELETE FROM public.asesor_curso_capacitacion a
USING public.asesor_curso_capacitacion b
WHERE a.id_asignacion_asesor > b.id_asignacion_asesor
  AND a.id_asesor = b.id_asesor
  AND a.id_curso_capacitacion = b.id_curso_capacitacion;

ALTER TABLE public.asesor_curso_capacitacion
    DROP CONSTRAINT IF EXISTS uq_asesor_curso_capacitacion;

ALTER TABLE public.asesor_curso_capacitacion
    ADD CONSTRAINT uq_asesor_curso_capacitacion
    UNIQUE (id_asesor, id_curso_capacitacion);

-- materia_curso_capacitacion
DELETE FROM public.materia_curso_capacitacion a
USING public.materia_curso_capacitacion b
WHERE a.id_asignacion_materia > b.id_asignacion_materia
  AND a.id_materia = b.id_materia
  AND a.id_curso_capacitacion = b.id_curso_capacitacion;

ALTER TABLE public.materia_curso_capacitacion
    DROP CONSTRAINT IF EXISTS uq_materia_curso_capacitacion;

ALTER TABLE public.materia_curso_capacitacion
    ADD CONSTRAINT uq_materia_curso_capacitacion
    UNIQUE (id_materia, id_curso_capacitacion);

COMMIT;
